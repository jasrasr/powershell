<#
.SYNOPSIS
Runs git-update against the approved GitHub repository allowlist.

.DESCRIPTION
Resolves each allowlisted repository name under -ParentPath, skips any that are
unavailable, and runs git-update in each one. Commit messages are generated by
git-update using the GIT_UPDATE_OPENAI_API_KEY environment variable unless -Quick
is used. Returns to the original directory when finished.

Depends on git-update (same module): git-update-all does not run any git commands or
call OpenAI itself. Every pull, commit, push, and commit-message step is done by
git-update, so git-update-all fails for every repository if git-update is missing.

-ParentPath defaults to the global $githubpath variable, which is expected to be
defined in the PowerShell profile. If neither is available, or the folder does not
exist, an info message is shown and nothing is run.

.PARAMETER ParentPath
Folder that contains the allowlisted repositories. Defaults to $githubpath.

.PARAMETER Quick
Skip AI and use timestamped commit messages in every repository.

.EXAMPLE
git-update-all
Run git-update in every allowlisted repository under $githubpath.

.EXAMPLE
git-update-all -Quick
Same, but with timestamped commit messages instead of AI-generated ones.

.EXAMPLE
git-update-all -ParentPath 'D:\Repos'
Resolve the allowlisted repositories under a different folder.

