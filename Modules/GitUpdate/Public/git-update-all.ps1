<#
.SYNOPSIS
Runs git-update against the approved GitHub repository allowlist.

.DESCRIPTION
Loops through the hard-coded repository allowlist, skips any that are unavailable,
and runs git-update in each one. Commit messages are generated by git-update using
the GIT_UPDATE_OPENAI_API_KEY environment variable unless -Quick is used.
Returns to the original directory when finished.

.PARAMETER ParentPath
Folder reported in the status messages. Defaults to the current directory. The
repository list itself is hard-coded and is not discovered from this path.

.PARAMETER Quick
Skip AI and use timestamped commit messages in every repository.

.EXAMPLE
git-update-all
Run git-update in every repository on the allowlist.

.EXAMPLE
git-update-all -Quick
Same, but with timestamped commit messages instead of AI-generated ones.

.NOTES
Filename : Public\git-update-all.ps1 (part of the GitUpdate module)
Revision : 1.2.0
Author   : Jason Lamb
Created  : 2026-06-13
Modified : 2026-10-19
Changelog:
