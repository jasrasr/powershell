function git-update-all {
    param(
        [Parameter(Mandatory = $false)]
        [string]$ParentPath = $global:githubpath,

        [Parameter(Mandatory = $false)]
        [switch]$Quick
    )

    if (-not $ParentPath) {
        Write-Host 'Info: -ParentPath was not provided and $githubpath is not defined. Define $githubpath in your PowerShell profile (the folder that contains your Git repositories) or run git-update-all -ParentPath <folder>.' -ForegroundColor Yellow
        return
    }

    if (-not (Test-Path -LiteralPath $ParentPath -PathType Container)) {
        Write-Host "Info: folder '$ParentPath' was not found. Check `$githubpath in your PowerShell profile or pass -ParentPath <folder>." -ForegroundColor Yellow
        return
    }

    $env:GIT_ASK_YESNO = 'false'

    # Approved repository allowlist (folder names under -ParentPath)
    $repositoryNames = @(
        'jasrasr.github.io'
        'jl-wp-plugins-pack'
        'jl-wp-theme-dark'
        'justjason-fyi'
        'powershell'
        'powershell-private'
        'website'
    )

    $repositories = @(
        foreach ($repositoryName in $repositoryNames) {
            $repositoryPath = Join-Path $ParentPath $repositoryName
            if (Test-Path -LiteralPath $repositoryPath -PathType Container) {
                [pscustomobject]@{
                    Name = $repositoryName
                    Path = $repositoryPath
                }
            } else {
                Write-Host "Skipping unavailable repository: $repositoryPath" -ForegroundColor Yellow
            }
        }
    )

    if ($repositories.Count -eq 0) {
        Write-Host "Info: none of the $($repositoryNames.Count) allowlisted repositories were found under '$ParentPath'." -ForegroundColor Yellow
        return
    }

    Write-Host "Found $($repositories.Count) of $($repositoryNames.Count) allowlisted Git repositories under '$ParentPath'." -ForegroundColor Cyan

    $originalLocation = (Get-Location).ProviderPath

    try {
        foreach ($repository in $repositories) {
            Write-Host ""
            Write-Host "=== $($repository.Name) ===" -ForegroundColor Magenta
            Write-Host $repository.Path -ForegroundColor DarkGray

            Push-Location -LiteralPath $repository.Path
            try {
                if ($Quick) {
                    git-update -Quick
                } else {
                    git-update
                }
            }
            catch {
                Write-Host "git-update failed for '$($repository.Path)': $_" -ForegroundColor Red
            }
            finally {
                Pop-Location
            }
        }
    }
    finally {
        Set-Location -LiteralPath $originalLocation
    }

    Write-Host ""
    Write-Host "Finished running git-update for allowlisted repositories." -ForegroundColor Green
}
